//! Key names to DirectInput scan codes (DIK_*).

pub fn dik(name: &str) -> Option<usize> {
    let n = name.to_ascii_lowercase();
    let code = match n.as_str() {
        "esc" | "escape" => 0x01,
        "1" => 0x02,
        "2" => 0x03,
        "3" => 0x04,
        "4" => 0x05,
        "5" => 0x06,
        "6" => 0x07,
        "7" => 0x08,
        "8" => 0x09,
        "9" => 0x0A,
        "0" => 0x0B,
        "tab" => 0x0F,
        "q" => 0x10,
        "w" => 0x11,
        "e" => 0x12,
        "r" => 0x13,
        "t" => 0x14,
        "y" => 0x15,
        "u" => 0x16,
        "i" => 0x17,
        "o" => 0x18,
        "p" => 0x19,
        "enter" | "return" => 0x1C,
        "ctrl" | "lctrl" => 0x1D,
        "a" => 0x1E,
        "s" => 0x1F,
        "d" => 0x20,
        "f" => 0x21,
        "g" => 0x22,
        "h" => 0x23,
        "j" => 0x24,
        "k" => 0x25,
        "l" => 0x26,
        "shift" | "lshift" => 0x2A,
        "z" => 0x2C,
        "x" => 0x2D,
        "c" => 0x2E,
        "v" => 0x2F,
        "b" => 0x30,
        "n" => 0x31,
        "m" => 0x32,
        "alt" | "lalt" => 0x38,
        "space" => 0x39,
        "f1" => 0x3B,
        "f2" => 0x3C,
        "f3" => 0x3D,
        "f4" => 0x3E,
        "f5" => 0x3F,
        "f6" => 0x40,
        "f7" => 0x41,
        "f8" => 0x42,
        "f9" => 0x43,
        "f10" => 0x44,
        "f11" => 0x57,
        "f12" => 0x58,
        "up" => 0xC8,
        "left" => 0xCB,
        "right" => 0xCD,
        "down" => 0xD0,
        _ => return None,
    };
    Some(code)
}
